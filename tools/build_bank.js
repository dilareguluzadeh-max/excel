"use strict";
/* node tools/build_bank.js  → exam_data.js + sual_banki_xeritesi.md
 * 5 variant × 6 tapşırıq. Hər variantda 6 FƏRQLİ modul; 8 modulun hamısı variantlar boyu əhatə olunur. */
const fs = require("fs"), path = require("path");
const SE = require("../sheetengine.js");
const { TASKS, MODULES } = require("./bank_excel.js");
const NV = 5, PER = 6, NAMES = "ABCDE";

function rng(seed) { let s = seed >>> 0; return () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
function shuffle(a, r) { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }

const byMod = {};
TASKS.forEach((t) => (byMod[t.mod] = byMod[t.mod] || []).push(t));

function attempt(seed) {
    const r = rng(seed);
    // modul-istifadə sayı: 6 modul 4 dəfə, 2 modul 3 dəfə (cəmi 30)
    const order = shuffle([1, 2, 3, 4, 5, 6, 7, 8], r);
    const need = {}; order.forEach((m, i) => (need[m] = i < 6 ? 4 : 3));
    const vars = Array.from({ length: NV }, () => []);
    // hər modulu NV variantdan need[m] fərqlisinə yerləşdir; hər variantda tam PER modul
    const mods = Object.keys(need).map(Number).sort((a, b) => need[b] - need[a]);
    const cap = Array(NV).fill(PER);
    for (const m of mods) {
        const idx = shuffle([0, 1, 2, 3, 4], r).sort((a, b) => cap[b] - cap[a]).slice(0, need[m]);
        for (const v of idx) { if (cap[v] <= 0) return null; vars[v].push(m); cap[v]--; }
    }
    if (cap.some((c) => c !== 0)) return null;
    // tapşırıqları seç: hər modul üçün tapşırıqlar təkrar olunmasın, çətinlik balanslı olsun
    const pool = {}; for (const m in byMod) pool[m] = shuffle(byMod[m], r);
    const out = vars.map(() => []);
    for (let v = 0; v < NV; v++) for (const m of vars[v]) {
        if (!pool[m].length) return null;
        out[v].push(pool[m].shift());
    }
    const sums = out.map((l) => l.reduce((s, t) => s + t.diff, 0));
    const spread = Math.max(...sums) - Math.min(...sums);
    return { out, spread, sums };
}
let best = null;
for (let s = 1; s < 4000; s++) { const a = attempt(s); if (a && (!best || a.spread < best.spread)) { best = a; best.seed = s; if (a.spread <= 1) break; } }
if (!best) throw new Error("variant split not found");

const md = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/`([^`]+)`/g, "<code>$1</code>").replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>");
function gridFor(t) {
    let mc = 6, mr = 10;
    const scan = (cells) => { for (const a of Object.keys(cells || {})) { const p = SE.parseAddr(a); mc = Math.max(mc, p.c + 2); mr = Math.max(mr, p.r + 3); } };
    scan(t.setup.cells); scan(t.sol.cells);
    for (const d of t.sol.dv || []) { const g = SE.parseRange(d.range); mc = Math.max(mc, g.c2 + 2); mr = Math.max(mr, g.r2 + 3); }
    return { cols: Math.min(mc, 12), rows: Math.min(Math.max(mr, 12), 18) };
}
function html(t) {
    return `<p class="xl-skill"><b>${MODULES[t.mod]}</b> · ${md(t.skill)}</p><ol class="xl-steps">${t.steps.map((s) => `<li>${md(s)}</li>`).join("")}</ol>`;
}

const variants = {}; const mapLines = [];
best.out.forEach((list, v) => {
    const r = rng(9000 + v * 17);
    const sorted = list.slice().sort((a, b) => b.diff - a.diff || a.n - b.n);
    const ptsOf = new Map(sorted.map((t, i) => [t.n, i < 4 ? 17 : 16]));
    const shuf = shuffle(list, r);
    const tasks = shuf.map((t, i) => ({
        id: "T" + (i + 1), title: t.title, pts: ptsOf.get(t.n), kind: "sheet", html: html(t),
        setup: { cells: t.setup.cells || {}, fmt: t.setup.fmt || {} }, grid: gridFor(t), checks: t.checks,
    }));
    const name = NAMES[v];
    variants[name] = { name: "Variant " + name, max_score: tasks.reduce((s, t) => s + t.pts, 0), items: tasks.map((t) => ({ type: "task", id: t.id })), tasks };
    mapLines.push(`## Variant ${name}  (${variants[name].max_score} points)\n\n| # | Bank | Module | Task | Points | Difficulty |\n|---|---|---|---|---|---|\n` +
        shuf.map((t, i) => `| T${i + 1} | ${t.n} | ${t.mod} | ${t.title} | ${ptsOf.get(t.n)} | ${t.diff} |`).join("\n"));
});
for (const k in variants) if (variants[k].max_score !== 100) throw new Error("bal 100 deyil: " + k);
fs.writeFileSync(path.join(__dirname, "..", "exam_data.js"),
    "// AUTO-GENERATED by node tools/build_bank.js — do not edit by hand.\nwindow.EXAM_DATA = " + JSON.stringify({ version: 3, kind: "excel", variants }, null, 1) + ";\n");
const cover = {}; Object.values(best.out).forEach((l) => l.forEach((t) => (cover[t.mod] = (cover[t.mod] || 0) + 1)));
fs.writeFileSync(path.join(__dirname, "..", "sual_banki_xeritesi.md"),
    "# Question bank map (Excel / Google Sheets)\n\n5 variants × 6 tasks = 100 points. Each variant has 6 different modules; number of variants using each module: " +
    Object.keys(MODULES).map((m) => `M${m}=${cover[m] || 0}`).join(", ") + ".\n\n" + mapLines.join("\n\n") + "\n");
console.log("seed", best.seed, "difficulty sums", best.sums.join(","), "module counts", JSON.stringify(cover));
